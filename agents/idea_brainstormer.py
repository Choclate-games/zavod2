_CATALOG: List[BrainstormedIdea] = _build_catalog()

# Идеи, показанные в прошлый раз: следующий вызов старается их не повторять,
# иначе кнопка «Придумать идею» каждый раз выдаёт одну и ту же пятёрку.
_recently_shown: List[str] = []


def catalog_size() -> int:
    return len(_CATALOG)


def _stem(word: str) -> str:
    """Грубый корень слова: отбрасывает русские окончания, но не короче четырёх букв."""
    stem = word.rstrip("аеёиоуыэюяьй")
    return stem if len(stem) >= 4 else word[:4]


def _matches_hint(idea: BrainstormedIdea, hint: str) -> bool:
    """Идея подходит подсказке, если та встречается в её тексте."""
    haystack = " ".join([
        idea.title, idea.genre, idea.hook, idea.pitch,
        idea.family, idea.art_style, idea.prompt_seed, idea.renderer,
    ]).lower()
    # Сравниваем по корню без окончания и только по началу слова: «гонки»
    # находят «гонка», но «расследование» уже не цепляет «рассыпьте».
    words = set(re.split(r"[^\w]+", haystack))
    roots = [_stem(w) for w in re.split(r"[^\w]+", hint.lower()) if len(w) >= 4]
    if not roots:
        return True
    return any(word.startswith(root) for word in words for root in roots if root)


def _pick(
    source: List[BrainstormedIdea],
    count: int,
    selected: List[BrainstormedIdea],
    used_families: set,
) -> None:
    """Добирает идеи: сначала по одной на семейство сеттинга, затем остальные."""
    for idea in source:
        if len(selected) >= count:
            return
        family = idea.family or idea.genre
        if family in used_families or idea in selected:
            continue
        used_families.add(family)
        selected.append(idea)
    for idea in source:
        if len(selected) >= count:
            return
        if idea not in selected:
            selected.append(idea)


def _shuffled_fresh_first(ideas: List[BrainstormedIdea]) -> List[BrainstormedIdea]:
    """Перемешивает идеи, отодвигая в конец показанные в прошлый раз."""
    pool = list(ideas)
    random.shuffle(pool)
    pool.sort(key=lambda idea: idea.title in _recently_shown)  # сортировка стабильная
    return pool


def fallback_catalog(theme_hint: str = "", count: int = 10) -> List[BrainstormedIdea]:
    """
    Встроенный каталог концептов — общий запасной вариант для брейнштормера и
    локального провайдера.

    Выдача не берётся «первыми N»: сначала отбирается по одной идее из каждого
    семейства сеттинга, поэтому десять идей приходят из десяти разных миров, а
    не из одного. Идеи, показанные в прошлый раз, уходят в конец очереди, а
    подходящие под подсказку — всегда впереди остальных.
    """
    global _recently_shown

    catalog = _CATALOG
    if not _wants_style(theme_hint):
        # Киберпанк и неон не предлагаются сами — только по прямой просьбе.
        catalog = [idea for idea in catalog if not _wants_style(f"{idea.art_style} {idea.title} {idea.genre}")]

    if theme_hint:
        matched = [idea for idea in catalog if _matches_hint(idea, theme_hint)]
        rest = [idea for idea in catalog if idea not in matched]
    else:
        matched, rest = list(catalog), []

    selected: List[BrainstormedIdea] = []
    used_families: set = set()
    _pick(_shuffled_fresh_first(matched), count, selected, used_families)
    if len(selected) < count:
        _pick(_shuffled_fresh_first(rest), count, selected, used_families)

    _recently_shown = [idea.title for idea in selected]
    return selected[:count]
