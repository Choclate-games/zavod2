# Фабрика выпускает игры только на Three.js. Значение зашито здесь, а не берётся
# из ответа модели: «pixijs» в поле рендерера уезжал в прогон как настоящий
# выбор и заказывал пакет под движок, которого у фабрики нет.
RENDERER = "threejs"


class GameTheme(BaseModel):
    """Заход в нишу: доказанный спрос плюс одно изменённое правило.

    Поля подобраны так, чтобы из них нельзя было вывести ни симулятор
    регламента, ни клон, ни перекраску. Порядок отражает приоритет: сначала
    ниша (в неё уже играют), потом что в ней остаётся как у всех, потом
    единственное правило, которое работает иначе, и только потом оболочка.

    Поля «что тут делают руками» здесь нет намеренно: пока оно было, шаг
    возвращал рабочую процедуру (ультразвуковая дефектоскопия каната,
    вакуумное напыление зеркала), а шаг игры честно превращал её в симулятор
    этой процедуры.

    Поле `unchanged` появилось после того, как выдача выродилась в подмену
    существительного: гонки, но на молоковозе; арена, но на ватрушках; башня,
    но маяк. Формально поворот был заявлен в каждой строке, а по правилам игры
    не менялось ничего. Когда модель обязана СНАЧАЛА написать, что она оставила
    как у всех, поворот перестаёт быть отпиской: перекраску туда не спрячешь,
    потому что рядом стоит строка о том, что правила прежние.
    """
    niche: str = Field(default="", description="Ниша с доказанным спросом, к которой относится игра")
    desire: str = Field(default="", description="Какое желание игрока эта ниша обслуживает")
    unchanged: str = Field(default="", description="Что в этой нише остаётся ровно как у всех: ядро, которое не трогаем")
    differentiator: str = Field(default="", description="ОДНО правило игры, которое работает не как обычно (не предмет и не декорация)")
    twist_target: str = Field(default="", description="Что именно меняет это правило: управление, условие победы, ресурс или противодействие")
    name: str = Field(description="Оболочка на русском: место, роль, среда, явление")
    spectacle: str = Field(default="", description="Что видно в кадре и на что интересно смотреть")
    verb: str = Field(default="", description="Одно главное физическое действие игрока: разгоняет, рушит, тянет, выращивает")
    tension: str = Field(default="", description="Что здесь может пойти не так: источник напряжения")


class ThemeResult(BaseModel):
    themes: List[GameTheme] = Field(default_factory=list)


class BrainstormedIdea(BaseModel):
    title: str = Field(description="Catchy game title in Russian")
    genre: str = Field(description="Main genre and subgenre in Russian")
    hook: str = Field(description="Viral unique gameplay hook / twist in Russian")
    pitch: str = Field(description="1-2 sentences explaining core game experience in Russian")
    # Рендерер не спрашивается у модели: он один на всю фабрику.
    renderer: str = Field(default=RENDERER, description="always threejs — the factory ships one renderer")
    platform_fit: str = Field(default="Яндекс Игры / Мобильные и ПК", description="Platform suitability in Russian")
    prompt_seed: str = Field(description="Complete ready-to-use prompt for generation in Russian")
    # Семейство сеттинга и визуальный стиль: по ним подбирается разнообразие
    # выдачи, чтобы десять идей не оказались десятью вариациями одной темы.
    family: str = Field(default="", description="Setting family in Russian, e.g. природа, кулинария, море")
    art_style: str = Field(default="", description="Visual style of the game in Russian")

class BrainstormResult(BaseModel):
    ideas: List[BrainstormedIdea] = Field(default_factory=list)

# Стили, которые фабрика не предлагает сама. Киберпанк и неон — не запрещённые
# темы, но они перестают быть визуальным умолчанием: их получают только те, кто
# прямо о них попросил.
UNSOLICITED_STYLES = ("киберпанк", "cyberpunk", "неон", "neon", "кибер")


def _wants_style(theme_hint: str, words=UNSOLICITED_STYLES) -> bool:
    """Просил ли пользователь стиль явно (например, киберпанк)."""
    lower = (theme_hint or "").lower()
    return any(word in lower for word in words)


