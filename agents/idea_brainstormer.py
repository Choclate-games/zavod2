# Кинематографические зачины, которыми модель начинает hook, когда её просят
# про зрелище. «Момент, когда пуля пробивает штифт…» — это половина строки, не
# сообщающая ничего: убрав её, получаем ту же фразу, только сразу по делу.
# Запрет стоит и в промпте; здесь — страховка, потому что на температуре 1.0
# формулировка-паразит возвращается примерно в каждой второй выдаче.
_FILLER_OPENERS = re.compile(
    r"^\s*(?:тот\s+самый\s+)?(?:момент|миг|секунда|мгновение)\s*,?\s*когда\s+"
    r"|^\s*представь(?:те)?\s*(?:себе)?\s*,?\s*(?:как|что)?\s+"
    r"|^\s*вообрази(?:те)?\s*,?\s*(?:как|что)?\s+",
    re.IGNORECASE,
)


def strip_filler_opener(text: str) -> str:
    """Срезает зачин-пустышку и возвращает фразу с заглавной буквы."""
    clean = _FILLER_OPENERS.sub("", text or "", count=1).lstrip()
    if clean and clean != (text or "").strip():
        clean = clean[0].upper() + clean[1:]
    return clean or (text or "")


def _avoid_line(seen: Sequence[str], prefix: str) -> str:
    """Строка «не повторяй вот это» — или пусто, если повторять ещё нечего."""
    unique: List[str] = []
    for item in seen:
        if item and item not in unique:
            unique.append(item)
    return f"{prefix}{'; '.join(unique[:24])}.\n" if unique else ""


def niches() -> List[dict]:
    """Ниши с доказанным спросом из `config/niches.yaml`.

    Читается на каждый запрос, а не кэшируется: список правится руками под
    аналитику площадок, и правка обязана действовать сразу, без перезапуска
    фабрики.
    """
    from app.config import config
    raw = (config.niches_cfg or {}).get("niches") or []
    return [n for n in raw if isinstance(n, dict) and (n.get("name") or "").strip()]


def _niches_block(limit: int = 12) -> str:
    """Список ниш для промпта: часть выборкой, чтобы выдача не застревала.

    Целиком список из восемнадцати ниш модель обрабатывает предсказуемо — берёт
    первые сверху. Случайная выборка на каждый вызов делает то же, что делали
    линзы: два нажатия подряд стартуют из разных мест.
    """
    pool = niches()
    if not pool:
        return ""
    chosen = random.sample(pool, k=min(limit, len(pool)))
    lines = ["НИШИ С ДОКАЗАННЫМ СПРОСОМ (в них уже играют массово):"]
    for niche in chosen:
        lines.append(f"\n- **{niche['name']}**")
        for label, key in (("желание", "desire"), ("сделано до дыр", "saturated")):
            value = str(niche.get(key) or "").strip()
            if value:
                lines.append(f"  - {label}: {value}")
        angles = [str(a).strip() for a in (niche.get("angles") or []) if str(a).strip()]
        if angles:
            lines.append(f"  - куда обычно не ходят: {'; '.join(angles)}")
    return "\n".join(lines)


def _theme_lines(index: int, theme: GameTheme) -> str:
    # Порядок полей — это подсказка о приоритете: ниша и поворот идут первыми,
    # оболочка и зрелище следом. Пока первым шло «что тут делают руками», шаг
    # игры честно строил механику вокруг порядка операций.
    head = f"{index}. **{theme.name}**"
    if (theme.niche or "").strip():
        head += f"  — ниша: {theme.niche.strip()}"
    parts = [head]
    twist = (theme.differentiator or "").strip()
    if twist and (theme.twist_target or "").strip():
        twist = f"{twist}  (меняет: {theme.twist_target.strip()})"
    for label, value in (("желание", theme.desire),
                         ("как у всех — не трогать", theme.unchanged),
                         ("изменённое правило", twist),
                         ("зрелище", theme.spectacle), ("действие", theme.verb),
                         ("напряжение", theme.tension)):
        if (value or "").strip():
            parts.append(f"   - {label}: {value.strip()}")
    return "\n".join(parts)


def _idea(title, family, genre, art_style, hook, pitch, renderer, platform_fit, prompt_seed) -> BrainstormedIdea:
    # `renderer` в записях каталога остался от времён, когда фабрика умела два
    # движка. Он больше не выбор: «pixijs» отсюда уезжал в прогон настоящим
    # заказом на движок, которого нет. Аргумент не удалён, чтобы не переписывать
    # три сотни строк каталога, — он просто ни на что не влияет.
    del renderer
    return BrainstormedIdea(
        title=title, family=family, genre=genre, art_style=art_style, hook=hook,
        pitch=pitch, renderer=RENDERER, platform_fit=platform_fit, prompt_seed=prompt_seed,
    )


