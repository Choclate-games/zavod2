from providers.base import AIProvider

class BrainstormedIdea(BaseModel):
    title: str = Field(description="Catchy game title in Russian")
    genre: str = Field(description="Main genre and subgenre in Russian")
    hook: str = Field(description="Viral unique gameplay hook / twist in Russian")
    pitch: str = Field(description="1-2 sentences explaining core game experience in Russian")
    renderer: str = Field(default="threejs", description="threejs or pixijs")
    platform_fit: str = Field(default="Яндекс Игры / Мобильные и ПК", description="Platform suitability in Russian")
    prompt_seed: str = Field(description="Complete ready-to-use prompt for generation in Russian")
    # Семейство сеттинга и визуальный стиль: по ним подбирается разнообразие
    # выдачи, чтобы десять идей не оказались десятью вариациями одной темы.
    family: str = Field(default="", description="Setting family in Russian, e.g. природа, кулинария, море")
    art_style: str = Field(default="", description="Visual style of the game in Russian")

class BrainstormResult(BaseModel):
    ideas: List[BrainstormedIdea] = Field(default_factory=list)

# Стили, которые фабрика не предлагает сама. Киберпанк и неон — не запрещённые
# темы, но они перестают быть визуальным умолчанием: их получают только те, кто
# прямо о них попросил.
UNSOLICITED_STYLES = ("киберпанк", "cyberpunk", "неон", "neon", "кибер")


def _wants_style(theme_hint: str, words=UNSOLICITED_STYLES) -> bool:
    """Просил ли пользователь стиль явно (например, киберпанк)."""
    lower = (theme_hint or "").lower()
    return any(word in lower for word in words)


class IdeaBrainstormerAgent:
    """
    AI Agent that brainstorms multiple viral, innovative HTML5/WebGL game concepts.
    Generates all output strictly in RUSSIAN language.
    """

    def brainstorm(
        self,
        ai_provider: Optional[AIProvider] = None,
        provider_name: str = "local",
        theme_hint: str = "",
        count: int = 10
    ) -> List[BrainstormedIdea]:
        if ai_provider is None:
            from providers.factory import ProviderFactory
            provider = ProviderFactory.get_ai_provider(provider_name)
        else:
            provider = ai_provider

        style_rule = (
            "Пользователь сам попросил этот стиль — держись его."
            if _wants_style(theme_hint)
            else (
                "STYLE RULE: не делай киберпанк, неон, «кибер-» и хай-тек-футуризм визуальным "
                "умолчанием — этот стиль допустим, только если пользователь прямо его попросил. "
                "Подбирай визуальный стиль под тему каждой идеи отдельно: акварель, винтаж, "
                "фольклор, натурализм, чертёж, бумага и тушь, ретро-космос, пастель и так далее."
            )
        )

        system_prompt = (
            "You are a visionary Game Director and Lead Concept Producer specializing in viral HTML5, WebGL, "
            "and mobile browser hits (Yandex Games, CrazyGames, Telegram WebApps, Playgama Bridge).\n"
            f"Generate exactly {count} distinct, highly engaging, innovative game concepts.\n"
            "DIVERSITY RULE: каждая идея — из своего сеттинга и своего жанрового семейства. "
            "Не повторяй сеттинг дважды и не своди список к боевикам: среди идей должны быть "
            "спокойные, ремесленные, повседневные, природные и головоломочные концепты, а не только "
            "арены, орды и рогалики.\n"
            f"{style_rule}\n"
            "CRITICAL LANGUAGE RULE:\n"
            "You MUST write all titles, genres, hooks, pitches, and prompts in RUSSIAN (на русском языке)!"
        )

        user_prompt = (
            f"Придумай {count} уникальных концептов игр для Яндекс Игр / WebGL.\n"
            f"Пожелания / Тема: '{theme_hint if theme_hint else 'Любой цепляющий концепт с высоким удержанием и понятной первой сессией'}'\n"
            "Разброс жанров обязателен: физические аркады, головоломки, менеджмент и симуляторы, "
            "нарративные и медитативные игры, ритм-игры, стелс, гонки, tower defense, idle, "
            "карточные рогалики, horde survival.\n"
            "Разброс сеттингов обязателен: природа, кулинария, ремесло, море, горы, деревня, "
            "фольклор, детектив, музыка, спорт, стройка, транспорт, космос, повседневность.\n"
            "Для каждой идеи заполни на русском языке: title, genre, hook, pitch, renderer "
            "(threejs/pixijs), platform_fit, family (семейство сеттинга), art_style (визуальный стиль), prompt_seed."
        )

        try:
            res = provider.generate_structured(system_prompt, user_prompt, BrainstormResult)
            if res and res.ideas:
                return res.ideas[:count]
        except Exception as e:
            print(f"[IdeaBrainstormer] Structured generation fallback: {e}")

        return self._get_fallback_catalog(theme_hint, count)

