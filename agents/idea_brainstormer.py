class BrainstormedIdea(BaseModel):
    title: str = Field(description="Catchy game title in Russian")
    genre: str = Field(description="Main genre and subgenre in Russian")
    hook: str = Field(description="Viral unique gameplay hook / twist in Russian")
    pitch: str = Field(description="1-2 sentences explaining core game experience in Russian")
    renderer: str = Field(default="threejs", description="threejs or pixijs")
    platform_fit: str = Field(default="Яндекс Игры / Мобильные и ПК", description="Platform suitability in Russian")
    prompt_seed: str = Field(description="Complete ready-to-use prompt for generation in Russian")
    # Семейство сеттинга и визуальный стиль: по ним подбирается разнообразие
    # выдачи, чтобы десять идей не оказались десятью вариациями одной темы.
    family: str = Field(default="", description="Setting family in Russian, e.g. природа, кулинария, море")
    art_style: str = Field(default="", description="Visual style of the game in Russian")

class BrainstormResult(BaseModel):
    ideas: List[BrainstormedIdea] = Field(default_factory=list)

# Стили, которые фабрика не предлагает сама. Киберпанк и неон — не запрещённые
# темы, но они перестают быть визуальным умолчанием: их получают только те, кто
# прямо о них попросил.
UNSOLICITED_STYLES = ("киберпанк", "cyberpunk", "неон", "neon", "кибер")


def _wants_style(theme_hint: str, words=UNSOLICITED_STYLES) -> bool:
    """Просил ли пользователь стиль явно (например, киберпанк)."""
    lower = (theme_hint or "").lower()
    return any(word in lower for word in words)


