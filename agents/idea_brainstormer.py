def _lenses(k: int = 3) -> List[str]:
    return random.sample(list(CREATIVE_LENSES), k=min(k, len(CREATIVE_LENSES)))


def _remember(ideas: List[BrainstormedIdea]) -> None:
    """Запоминает выданные заголовки, чтобы следующий вызов их не повторял."""
    global _recently_shown
    _recently_shown = [idea.title for idea in ideas]


class IdeaBrainstormerAgent:
    """
    AI Agent that brainstorms multiple viral, innovative HTML5/WebGL game concepts.
    Generates all output strictly in RUSSIAN language.
    """

    def brainstorm(
        self,
        ai_provider: Optional[AIProvider] = None,
        provider_name: str = "default",   # офлайн-режим отключён, см. ProviderFactory
        theme_hint: str = "",
        count: int = 10
    ) -> List[BrainstormedIdea]:
        if ai_provider is None:
            from providers.factory import ProviderFactory
            provider = ProviderFactory.get_ai_provider(provider_name)
        else:
            provider = ai_provider

        style_rule = (
            "Пользователь сам попросил этот стиль — держись его."
            if _wants_style(theme_hint)
            else (
                "Единственное стилевое ограничение: киберпанк, неон и хай-тек-футуризм не должны "
                "быть визуальным умолчанием — этот стиль уместен, только если игрок прямо его "
                "попросил. Всё остальное открыто: стиль подбирай под каждую идею отдельно."
            )
        )

        system_prompt = (
            "You are a visionary Game Director and Lead Concept Producer specializing in viral HTML5, WebGL, "
            "and mobile browser hits (Yandex Games, CrazyGames, Telegram WebApps, Playgama Bridge).\n"
            f"Generate exactly {count} distinct game concepts.\n"
            "FREEDOM RULE: у тебя нет списка разрешённых жанров и сеттингов — предлагай что угодно, "
            "включая то, чего в браузерных играх обычно не делают. Не выбирай тему потому, что она "
            "«безопасная»: ценнее концепт, который трудно спутать с чужой игрой. Не сводись к "
            "привычному набору (арены, орды, рогалики, три-в-ряд), но и не избегай его, если у тебя "
            "есть свежий поворот.\n"
            "DIVERSITY RULE: все идеи — из разных миров и разных жанровых семейств, ни один сеттинг "
            "не повторяется дважды. Хотя бы половина списка — не про бой: ремесло, быт, природа, "
            "исследование, головоломка, наблюдение, отношения.\n"
            "Каждая идея обязана быть выполнима в браузере небольшой командой: понятная первая "
            "сессия, управление мышью или свайпом, короткая петля.\n"
            f"{style_rule}\n"
            "CRITICAL LANGUAGE RULE:\n"
            "You MUST write all titles, genres, hooks, pitches, and prompts in RUSSIAN (на русском языке)!"
        )

        avoid = ""
        if _recently_shown:
            avoid = (
                "В прошлый раз уже показывали: "
                + "; ".join(_recently_shown[:12])
                + ". Не повторяй ни эти идеи, ни их сеттинги — придумай другое.\n"
            )

        theme_line = (
            f"Пожелания / Тема: '{theme_hint}'\n"
            if theme_hint
            else "Тему выбираешь сам — ограничений нет.\n"
        )

        user_prompt = (
            f"Придумай {count} уникальных концептов игр для Яндекс Игр / WebGL.\n"
            f"{theme_line}"
            f"{avoid}"
            "Чтобы сбить инерцию, вот несколько случайных отправных точек. Это поводы, а не "
            "задание — часть идей может прийти совсем из другого места:\n"
            + "\n".join(f"- {lens}" for lens in _lenses(3))
            + "\n"
            "Для каждой идеи заполни на русском языке: title, genre, hook, pitch, renderer "
            "(threejs/pixijs), platform_fit, family (семейство сеттинга), art_style (визуальный стиль), prompt_seed."
        )

        try:
            # Высокая температура: это брейншторм, а не извлечение фактов —
            # осторожная выдача здесь и означает «десять раз одно и то же».
            res = provider.generate_structured(
                system_prompt, user_prompt, BrainstormResult, temperature=1.0
            )
            if res and res.ideas:
                ideas = res.ideas[:count]
                _remember(ideas)
                return ideas
        except Exception as e:
            print(f"[IdeaBrainstormer] Structured generation fallback: {e}")

        return self._get_fallback_catalog(theme_hint, count)

    def _get_fallback_catalog(self, theme_hint: str, count: int) -> List[BrainstormedIdea]:
        return fallback_catalog(theme_hint, count)

