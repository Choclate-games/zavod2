def _lenses(k: int = 3) -> List[str]:
    return random.sample(list(CREATIVE_LENSES), k=min(k, len(CREATIVE_LENSES)))


# Скользящая память выдач. Держится в процессе фабрики: перезапуск её обнуляет,
# и это осознанно — список «не предлагай» длиной в месяц сам становится рамкой.
_MEMORY_LIMIT = 60
_recently_shown: List[str] = []
_recent_families: List[str] = []


def _remember(ideas: List[BrainstormedIdea]) -> None:
    """Копит показанное, чтобы следующий вызов туда не возвращался.

    Раньше помнилась только последняя выдача, и на третьем нажатии «Придумать
    идею» спокойно возвращалась тема со второго. Держим скользящее окно на
    несколько заходов — и по названиям, и по семействам сеттингов, потому что
    повтор темы заметнее повтора заголовка.
    """
    global _recently_shown, _recent_families
    _recently_shown = ([idea.title for idea in ideas] + _recently_shown)[:_MEMORY_LIMIT]
    families = [(idea.family or idea.genre).strip() for idea in ideas]
    _recent_families = ([f for f in families if f] + _recent_families)[:_MEMORY_LIMIT]


def remember_titles(titles: Sequence[str]) -> None:
    """Досыпает в память названия уже выпущенных игр.

    Фабрика знает, что она уже сделала, а брейнштормер — нет: он раз за разом
    предлагал вариацию игры, которая лежит в соседней папке. Список приходит из
    веб-сервиса перед вызовом.
    """
    global _recently_shown
    clean = [t.strip() for t in titles if t and t.strip()]
    _recently_shown = (clean + _recently_shown)[:_MEMORY_LIMIT]


class BrainstormFailed(RuntimeError):
    """Модель не вернула идеи.

    Отдельный тип, а не молчаливая подстановка каталога: подменённый ответ
    неотличим от настоящего, и человек видел «ИИ придумал», глядя на тот же
    список, что и в прошлый раз. Пусть лучше в интерфейсе будет ошибка.
    """


