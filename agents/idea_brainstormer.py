"""Генератор идей: сначала модель придумывает тематики, потом делает из них игры.

Почему в два захода
-------------------
Один вопрос «придумай десять концептов» модель отрабатывает так же, как любой
другой: выдаёт самое вероятное продолжение. Самое вероятное продолжение слова
«концепт игры» — уже существующая игра, слегка перекрашенная. Отсюда и брались
десять вариаций Vampire Survivors, Subway Surfers и «три в ряд с котиками» в
разных обёртках: модель не ленилась, она отвечала ровно на заданный вопрос.

Поэтому вопросов теперь два, и первый — не про игры:

  1. **Тематика.** Область человеческой жизни, ремесло, среда, явление. Заказа
     на игру в этом шаге нет вовсе — слово «игра» встречается разве что в
     отрицании («про это игр не делают»), поэтому вспоминать чужие релизы
     модели не с чего: она идёт за темой.
  2. **Игра из тематики.** Механика выводится из того, что в этой области
     делают руками, и из того, что в ней видно глазом. Жанр здесь — вывод, а
     не заготовка, в которую тему покрасили.

Рендерер один: фабрика выпускает игры только на Three.js (`app/knowledge.RENDERER`).
2D — это та же сцена под ортографической камерой, а не второй движок.

Осечка провайдера остаётся осечкой (см. AGENT.md, «Правила работы с
провайдерами»): подставлять вместо ответа модели встроенный каталог запрещено —
именно это годами и выглядело как «ИИ опять всё скопировал». Каталог остался
только у офлайн-провайдера, которого выбирает человек.
"""
