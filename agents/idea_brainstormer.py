    def brainstorm(
        self,
        ai_provider: Optional[AIProvider] = None,
        provider_name: str = "default",   # офлайн-режим отключён, см. ProviderFactory
        theme_hint: str = "",
        count: int = 10
    ) -> List[BrainstormedIdea]:
        if ai_provider is None:
            from providers.factory import ProviderFactory
            provider = ProviderFactory.get_ai_provider(provider_name)
        else:
            provider = ai_provider

        themes = self._invent_themes(provider, theme_hint, count)
        ideas = self._design_games(provider, themes, theme_hint, count)
        if not ideas:
            raise BrainstormFailed(
                "Модель не вернула ни одной идеи. Проверьте выбранного провайдера "
                "(кнопка «🔌 Проверить» в настройках) и повторите — подставлять "
                "заготовленный список фабрика не будет."
            )
        _remember(ideas)
        return ideas

