def _palette_from_prompt(prompt: str) -> Dict[str, tuple]:
    """Достаёт HEX-цвета из промпта превью и раскладывает их по ролям.

    Промпт собирает `PreviewDesignerAgent`, поэтому цвета в нём — это палитра
    самой игры. Если их нет (например, промпт писали руками), берётся спокойная
    нейтральная гамма, а не неон.
    """
    hex_codes = re.findall(r"#([0-9a-fA-F]{6})", prompt)
    colors = [tuple(int(code[i:i + 2], 16) for i in (0, 2, 4)) for code in hex_codes]
    defaults = [(76, 159, 112), (224, 122, 95), (242, 204, 143), (30, 34, 43), (44, 49, 60)]
    colors = (colors + defaults)[:5]
    return {
        "primary": colors[0],
        "secondary": colors[1],
        "accent": colors[2],
        "background": colors[3],
        "surface": colors[4],
    }


class LocalImageProvider(ImageProvider):
    """Procedural local image generator that produces high-resolution concept mockups."""

    def generate_image(
        self,
        prompt: str,
        output_path: Path,
        aspect_ratio: str = "16:9",
        width: int = 1280,
        height: int = 720
    ) -> bool:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        try:
            # Цвета берём из палитры, переданной в промпте: заглушка должна
            # попадать в стиль игры, а не быть вечно неоновой.
            palette = _palette_from_prompt(prompt)
            background = palette["background"]
            primary, secondary, accent, surface = (
                palette["primary"], palette["secondary"], palette["accent"], palette["surface"],
            )

            img = Image.new("RGBA", (width, height), background + (255,))
            draw = ImageDraw.Draw(img)

            cx, cy = width // 2, height // 2
            # Плоскость сцены: перспективная сетка в цвете акцента
            for i in range(0, width, 40):
                draw.line([(i, cy), (i + (i - cx) * 2, height)], fill=accent + (28,), width=1)
            for y in range(cy, height, 25):
                draw.line([(0, y), (width, y)], fill=accent + (28,), width=1)

            # Игровая площадка
            draw.polygon([
                (cx - 300, cy + 180),
                (cx + 300, cy + 180),
                (cx + 180, cy - 20),
                (cx - 180, cy - 20)
            ], fill=surface + (210,), outline=primary + (180,), width=3)

            # Игрок и действие
            draw.ellipse([cx - 30, cy + 80, cx + 30, cy + 140], fill=primary + (230,), outline=(255, 255, 255), width=2)
            draw.ellipse([cx + 100, cy + 50, cx + 150, cy + 100], fill=secondary + (230,), outline=accent + (255,), width=3)
            draw.line([(cx + 10, cy + 100), (cx + 100, cy + 75)], fill=primary + (240,), width=4)

            # HUD
            draw.rectangle([30, 25, 280, 55], fill=surface + (220,), outline=primary + (180,), width=2)
            draw.rectangle([34, 29, 230, 51], fill=primary + (230,))
            draw.rectangle([width - 250, 25, width - 30, 55], fill=surface + (220,), outline=accent + (180,), width=2)

            # Тач-управление
            draw.ellipse([50, height - 150, 150, height - 50], outline=primary + (150,), width=3)
            draw.ellipse([80, height - 120, 120, height - 80], fill=primary + (180,))
            draw.ellipse([width - 140, height - 140, width - 60, height - 60], fill=secondary + (200,), outline=(255, 255, 255), width=3)

            # Текст
            draw.text((cx - 160, 40), "AI GAME CONCEPT PREVIEW", fill=(240, 244, 252, 230))

            img.convert("RGB").save(output_path, "PNG")
            return True
        except Exception as e:
            print(f"Error in LocalImageProvider: {e}")
            return False
