    @classmethod
    def _clean_prompt(cls, raw_prompt: str) -> str:
        """Убирает служебные строки агентов, оставляя саму идею игрока."""
        lines = []
        for line in (raw_prompt or "").splitlines():
            stripped = line.strip()
            lowered = stripped.lower()
            if any(lowered.startswith(prefix) for prefix in cls._PROMPT_NOISE):
                for prefix in cls._PROMPT_NOISE:
                    if lowered.startswith(prefix):
                        stripped = stripped[len(prefix):].strip()
                        break
                if not stripped:
                    continue
            if stripped:
                lines.append(stripped)
        return " ".join(lines).strip() or (raw_prompt or "").strip()

    @classmethod
    def _title_from_prompt(cls, idea: str) -> str:
        """Собирает название из первых значимых слов идеи."""
        words = [w for w in re.split(r"\s+", idea) if w]
        skip = {"игра", "игру", "про", "для", "на", "в", "и", "с", "2d", "3d", "сделай", "создай"}
        meaningful = [w for w in words if w.lower().strip(",.:;") not in skip]
        title = " ".join((meaningful or words)[:4]).strip(" ,.:;-")
        return title[:48].capitalize() if title else "Новая игра"

    @classmethod
    def _slugify(cls, text: str) -> str:
        """Латинский слаг из русского названия — иначе папка получает заглушку."""
        latin = "".join(cls._TRANSLIT.get(ch, ch) for ch in text.lower())
        slug = re.sub(r"[^a-z0-9]+", "-", latin).strip("-")
        return slug[:40] or "game-project"

