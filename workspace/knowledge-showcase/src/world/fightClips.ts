/**
 * Мокап поверх позы-цели: клипы из `assets/fight_anim/`, запечённые в
 * повороты драйверов рига (`scripts/bake-fight-anim.ts`).
 *
 * Клипы **не заменяют** анимацию из фрейм-даты, а домешиваются к ней. Причин
 * две, и обе выяснились на этих 40 файлах:
 *
 * 1. **Стойки и шагов в наборе нет.** Есть удары, блоки, уклоны, падения и
 *    подъём — то есть всё, что происходит «иногда». То, что боец делает
 *    большую часть матча (стоит в стойке, качается, шагает), по-прежнему
 *    считает `poseRig()`.
 * 2. **Длительность клипа не равна длительности приёма.** Мокапный джеб —
 *    0.93 с, джеб в игре — 4/3/9 кадров, то есть 0.27 с. Клип проигрывается
 *    не «как записан», а растянутый ровно на свою фрейм-дату: иначе анимация
 *    и хитбоксы разъезжаются, и это худший баг файтинга — игрок видит
 *    попадание, которого игра не засчитала.
 *
 * Смешивание одностороннее: сначала кадр собирает поза-цель, потом клип
 * тянет драйверы к себе с весом. Выход из клипа поэтому бесшовный — как
 * только вес пропал, экспоненциальное приближение позы-цели доводит бойца до
 * стойки из той позы, в которой его оставил мокап.
 */

/** Один запечённый клип: повороты драйверов по кадрам. */
export interface FightClip {
  frames: number;
  /** Смещение таза по вертикали относительно первого кадра, метры. */
  rootY: number[];
  /** Ключ — имя драйвера в `BoxerRig`, значение — xyzw по кадрам. */
  joints: Record<string, number[]>;
}

export type FightClips = Map<string, FightClip>;

/** Как состояние бойца пользуется клипом. */
export interface ClipUse {
  clip: string;
  /** Окно клипа, доли: мокап часто начинается с ленивого замаха. */
  from?: number;
  to?: number;
  /** Вес подмешивания, 0..1. Меньше единицы — «мокап, но своей стойкой». */
  weight?: number;
  /**
   * Держать один кадр вместо проигрывания. Для состояний без длительности
   * (блок, присед) прогресс брать неоткуда: боец стоит в них сколько хочет.
   */
  hold?: number;
  /**
   * Что берём из клипа. По умолчанию — только верх тела.
   *
   * Мокап записан со своим движением корня: актёр шагает, приседает и
   * переносит вес. У бойца корнем распоряжается игра — она держит его на
   * настиле, сводит дистанцию и толкает откидыванием. Если отдать мокапу ещё
   * и таз с ногами, эти двое начинают спорить: боец наклоняется вперёд
   * всем телом, стопы отрываются от настила и висят, а колени доворачиваются
   * туда, куда их вёл актёр. На кадрах ударов это выглядело как полёт в позе
   * ныряльщика.
   *
   * Поэтому по умолчанию клип — это верхний слой: позвоночник, голова, руки.
   * `full` берут только те анимации, где ноги и есть смысл движения (удар с
   * воздуха, подъём с настила).
   */
  layer?: 'torso' | 'upper' | 'full';
  /**
   * Точный список драйверов вместо слоя.
   *
   * Слои — грубая мерка: «верх» или «всё». Удару ногой не подходит ни то,
   * ни другое. «Верх» отдаёт ноги позе-цели, и тогда мокап ноги вообще не
   * участвует — ради чего его тогда записывали. «Всё» отдаёт мокапу и таз,
   * и ОПОРНУЮ ногу, а её ведёт игра: боец привязан к своей точке настила,
   * и актёрский перенос веса отрывает ему стопу от пола.
   *
   * Правильная граница проходит по бьющей конечности: мокап ведёт ту ногу,
   * которая бьёт, игра — вторую, таз и корень. Здесь этот список и живёт.
   */
  joints?: readonly string[];
}

/** Суставы верхнего слоя: всё, что выше таза. */
