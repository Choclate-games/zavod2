export async function loadFightClips(url = 'models/fight_anim.json'): Promise<FightClips> {
  const bytes = await readAsset(url);
  const data = JSON.parse(new TextDecoder().decode(bytes)) as { clips: Record<string, FightClip> };
  return new Map(Object.entries(data.clips));
}

const _a = new THREE.Quaternion();
const _b = new THREE.Quaternion();

/**
 * Домешать кадр клипа в риг.
 *
 * `progress` — 0..1 по приёму, а не по клипу: окно `from..to` выбирается
 * здесь. `weight` — насколько мокап перетягивает уже собранную позу.
 */
export function applyFightClip(
  rig: BoxerRig,
  clips: FightClips,
  use: ClipUse,
  progress: number,
  weight = 1,
): void {
  const clip = clips.get(use.clip);
  if (!clip || clip.frames < 2) return;
  const w = THREE.MathUtils.clamp(weight * (use.weight ?? 1), 0, 1);
  if (w <= 0.001) return;

  const from = use.from ?? 0;
  const to = use.to ?? 1;
  const t = use.hold ?? (from + THREE.MathUtils.clamp(progress, 0, 1) * (to - from));
  const pos = THREE.MathUtils.clamp(t, 0, 1) * (clip.frames - 1);
  const i0 = Math.floor(pos);
  const i1 = Math.min(clip.frames - 1, i0 + 1);
  const f = pos - i0;

  const layer = use.layer ?? 'upper';
  const allowed = use.joints
    ? new Set(use.joints)
    : (layer === 'full' ? null : (layer === 'torso' ? TORSO : UPPER));
  for (const key in clip.joints) {
    if (allowed && !allowed.has(key)) continue;
    const target = rig[key as keyof BoxerRig] as THREE.Object3D | undefined;
    const track = clip.joints[key];
    if (!target || !track) continue;
    _a.set(track[i0 * 4], track[i0 * 4 + 1], track[i0 * 4 + 2], track[i0 * 4 + 3]);
    _b.set(track[i1 * 4], track[i1 * 4 + 1], track[i1 * 4 + 2], track[i1 * 4 + 3]);
    _a.slerp(_b, f);
    target.quaternion.slerp(_a, w);
  }

  // Высота таза — это ноги, и вне полного слоя её не трогаем. Явный список
  // суставов корень не отдаёт никогда: он для того и нужен, чтобы взять из
  // клипа конечность, оставив игре её точку на настиле.
  if (layer !== 'full' || use.joints) return;
  const rootY = clip.rootY[i0] + (clip.rootY[i1] - clip.rootY[i0]) * f;
  const d = rig.defaults;
  rig.body.position.y += (d.bodyPos.y + rootY - rig.body.position.y) * w;
  rig.hips.position.y += (d.hipsY + rootY - rig.hips.position.y) * w;
}
